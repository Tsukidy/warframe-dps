//! Generated artefacts of the model, written by `cargo xtask gen-ts` and `cargo xtask gen-schema` (T01b):
//!
//! - [`typescript_files`] (feature `ts`): the TypeScript declarations of every API route type and the documents,
//!   with their dependencies (ts-rs; one file per type), plus `messageKeys.ts` (every message key the server emits,
//!   [`crate::message::all_keys`]) and an `index.ts` that re-exports everything. Output directory:
//!   `frontend/src/api/generated/`.
//! - [`curated_schema_json`] (features `schema` and `curated`): the JSON schema of the curated TOML files for editor
//!   validation (pipeline.md §6.1), written to `data/curated/schema.json`.
//!
//! Both are pure functions of the model, so `--check` regenerates them in memory and compares.

#[cfg(feature = "ts")]
pub use typescript::*;

#[cfg(feature = "ts")]
mod typescript {
    use crate::api::*;
    use crate::message::Message;
    use crate::scenario::CalcInput;
    use std::any::TypeId;
    use std::collections::BTreeMap;
    use ts_rs::{Config, TS, TypeVisitor};

    /// Header of the files this module writes itself (ts-rs writes its own note into the type files).
    pub const GENERATED_NOTE: &str = "// This file was generated by `cargo xtask gen-ts` (wfd-model). Do not edit this file manually.\n";

    /// File name of the message-key list.
    pub const MESSAGE_KEYS_FILE: &str = "messageKeys.ts";

    /// File name of the barrel file.
    pub const INDEX_FILE: &str = "index.ts";

    /// Collects the declaration of every exportable type reachable from the roots.
    struct Collector {
        cfg: Config,
        seen: std::collections::HashSet<TypeId>,
        files: BTreeMap<String, (TypeId, String)>,
        roots: Vec<String>,
        error: Option<String>,
    }

    impl Collector {
        fn root<T: TS + 'static>(&mut self) {
            self.roots.push(T::name(&self.cfg));
            self.add::<T>();
        }

        fn add<T: TS + 'static + ?Sized>(&mut self) {
            if self.error.is_some() || !self.seen.insert(TypeId::of::<T>()) {
                return;
            }
            let Some(path) = T::output_path() else {
                return;
            };
            let path = path.to_string_lossy().replace('\\', "/");
            let text = match T::export_to_string(&self.cfg) {
                Ok(t) => t,
                Err(e) => {
                    self.error = Some(format!("{}: {e}", std::any::type_name::<T>()));
                    return;
                }
            };
            match self.files.get(&path) {
                // Generic instantiations share one declaration.
                Some((_, old)) if *old == text => {}
                Some(_) => {
                    self.error = Some(format!(
                        "two different types export to {path} (rename one with #[ts(rename)]): {}",
                        std::any::type_name::<T>()
                    ));
                    return;
                }
                None => {
                    self.files.insert(path, (TypeId::of::<T>(), text));
                }
            }
            T::visit_dependencies(self);
        }
    }

    impl TypeVisitor for Collector {
        fn visit<T: TS + 'static + ?Sized>(&mut self) {
            self.add::<T>();
        }
    }

    /// Adds every root type of the API (route bodies and responses, SSE events, documents).
    fn add_roots(c: &mut Collector) {
        // Documents (server-api.md §4) and shared shapes.
        c.root::<CalcInput>();
        c.root::<Message>();
        c.root::<ErrorResponse>();
        // §5 catalogue and schema routes.
        c.root::<Meta>();
        c.root::<Catalog>();
        c.root::<WeaponDetail>();
        c.root::<ItemDetail>();
        c.root::<EnemyDetail>();
        c.root::<ScenarioSchema>();
        c.root::<CandidatesRequest>();
        c.root::<Candidate>();
        // §6 calculation routes.
        c.root::<CalcRequest>();
        c.root::<CalcReport>();
        c.root::<TimelineRequest>();
        c.root::<Timeline>();
        c.root::<ExplainRequest>();
        c.root::<Explanation>();
        // §7 build-code routes.
        c.root::<EncodeResponse>();
        c.root::<DecodeRequest>();
        c.root::<DecodeResponse>();
        c.root::<ExportInspirationResponse>();
        // §8 optimizer routes and events.
        c.root::<OptRequest>();
        c.root::<JobAccepted>();
        c.root::<OptEvent>();
        c.root::<OptResult>();
        c.root::<JobStatus<OptResult>>();
        // §9 data routes and events.
        c.root::<DataStatus>();
        c.root::<DataCheck>();
        c.root::<RefreshRequest>();
        c.root::<ActivateRequest>();
        c.root::<DataEvent>();
    }

    fn collect() -> Result<Collector, String> {
        let mut c = Collector {
            // Large integers stay `bigint`: every u64 of an API type must carry `#[ts(type = "number")]`, and the
            // tests fail on any `bigint` in the output (domain-model.md §1).
            cfg: Config::new(),
            seen: Default::default(),
            files: BTreeMap::new(),
            roots: Vec::new(),
            error: None,
        };
        add_roots(&mut c);
        match c.error.take() {
            Some(e) => Err(e),
            None => Ok(c),
        }
    }

    /// TypeScript names of the root types (`"CalcReport"`, `"JobStatus<OptResult>"` …): route bodies and responses,
    /// SSE events, documents.
    pub fn typescript_roots() -> Result<Vec<String>, String> {
        Ok(collect()?.roots)
    }

    /// The generated files: relative path (`"CalcReport.ts"`) → content. Deterministic; fails when two types would
    /// share a file or a type cannot be exported.
    pub fn typescript_files() -> Result<BTreeMap<String, String>, String> {
        let c = collect()?;
        let mut out: BTreeMap<String, String> =
            c.files.into_iter().map(|(p, (_, t))| (p, t)).collect();
        for name in [MESSAGE_KEYS_FILE, INDEX_FILE] {
            if out.contains_key(name) {
                return Err(format!("a type exports to {name}"));
            }
        }
        out.insert(MESSAGE_KEYS_FILE.into(), message_keys_ts());
        let mut index = String::from(GENERATED_NOTE);
        index.push('\n');
        for path in out.keys() {
            let module = path.strip_suffix(".ts").unwrap_or(path);
            index.push_str(&format!("export * from \"./{module}\";\n"));
        }
        out.insert(INDEX_FILE.into(), index);
        Ok(out)
    }

    /// `messageKeys.ts`: every message key the server emits with its area and argument names.
    fn message_keys_ts() -> String {
        let mut s = String::from(GENERATED_NOTE);
        s.push_str(
            "\n/** Every message key the server emits (wfd-model `message::all_keys`): area and argument names. Keys \
             of curated data (toggle, parameter and riven-trait labels) come with the schema route instead. */\n",
        );
        s.push_str("export const MESSAGE_KEYS = {\n");
        for k in crate::message::all_keys() {
            let args: Vec<String> = k.args.iter().map(|a| format!("\"{a}\"")).collect();
            s.push_str(&format!(
                "  \"{}\": {{ area: \"{}\", args: [{}] }},\n",
                k.key,
                k.area,
                args.join(", ")
            ));
        }
        s.push_str("} as const;\n\n");
        s.push_str("/** A message key the server emits. */\n");
        s.push_str("export type KnownMessageKey = keyof typeof MESSAGE_KEYS;\n");
        s
    }
}

#[cfg(all(feature = "schema", feature = "curated"))]
pub use curated_schema::*;

#[cfg(all(feature = "schema", feature = "curated"))]
mod curated_schema {
    use crate::curated::*;
    use schemars::SchemaGenerator;

    /// Which definition of `data/curated/schema.json` describes which curated file (pipeline.md §6.1). The root of
    /// the schema is `CuratedItemFile`, the item files that make up most of the directory.
    pub const CURATED_FILE_SCHEMAS: &[(&str, &str)] = &[
        (
            "weapon_mod/**, weapon_arcane/**, frame_mod/**, aura/**, frame_arcane/**, shard/**, stance/**, set/**, \
             buff/**, custom/**",
            "CuratedItemFile",
        ),
        ("incarnon/**", "IncarnonFamilyFile"),
        ("rules/mult_groups.toml", "MultGroupsFile"),
        ("rules/slot_layout.toml", "SlotLayoutFile"),
        ("rules/riven_traits.toml", "RivenTraitsFile"),
        ("rules/riven_formula.toml", "RivenFormulaFile"),
        ("rules/body_parts.toml", "BodyPartsFile"),
        ("rules/special_dr.toml", "SpecialDrFile"),
        ("rules/toggles.toml", "TogglesFile"),
        ("rules/factions.toml", "FactionsFile"),
        ("rules/categories.toml", "CategoriesFile"),
        ("rules/helminth.toml", "HelminthFile"),
        ("rules/frames.toml", "FramesFile"),
        ("rules/attack_roles.toml", "AttackRolesFile"),
        ("rules/stat_lines.toml", "StatLinesFile"),
        ("rules/melee/heavy_class.toml", "HeavyClassFile"),
        ("rules/melee/heavy_kappa.toml", "HeavyKappaFile"),
        ("rules/melee/attack_triggers.toml", "AttackTriggersFile"),
        ("rules/melee/stance_co.toml", "StanceCoFile"),
        ("rules/melee/finishers.toml", "FinishersFile"),
        ("rules/melee/combo_specials.toml", "ComboSpecialsFile"),
    ];

    /// The JSON schema of the curated files, pretty-printed with a final newline: root `CuratedItemFile` (the header of
    /// domain-model.md §15.1 and the `EffectDef`s of §11), every other curated file type under `$defs`
    /// ([`CURATED_FILE_SCHEMAS`]).
    pub fn curated_schema_json() -> String {
        let mut g = SchemaGenerator::default();
        g.subschema_for::<IncarnonFamilyFile>();
        g.subschema_for::<MultGroupsFile>();
        g.subschema_for::<SlotLayoutFile>();
        g.subschema_for::<RivenTraitsFile>();
        g.subschema_for::<RivenFormulaFile>();
        g.subschema_for::<BodyPartsFile>();
        g.subschema_for::<SpecialDrFile>();
        g.subschema_for::<TogglesFile>();
        g.subschema_for::<FactionsFile>();
        g.subschema_for::<CategoriesFile>();
        g.subschema_for::<HelminthFile>();
        g.subschema_for::<FramesFile>();
        g.subschema_for::<AttackRolesFile>();
        g.subschema_for::<StatLinesFile>();
        g.subschema_for::<HeavyClassFile>();
        g.subschema_for::<HeavyKappaFile>();
        g.subschema_for::<AttackTriggersFile>();
        g.subschema_for::<StanceCoFile>();
        g.subschema_for::<FinishersFile>();
        g.subschema_for::<ComboSpecialsFile>();
        let mut schema = g.into_root_schema_for::<CuratedItemFile>();
        let map: Vec<String> = CURATED_FILE_SCHEMAS
            .iter()
            .map(|(files, def)| format!("{files} → {def}"))
            .collect();
        schema.insert(
            "$comment".into(),
            format!(
                "GENERATED by `cargo xtask gen-schema` (wfd-model) — never edit by hand. Curated TOML files of \
                 pipeline.md §6.1. The root describes the item files; the other files are described under $defs: {}.",
                map.join("; ")
            )
            .into(),
        );
        let mut text = serde_json::to_string_pretty(&schema).expect("a schema serializes");
        text.push('\n');
        text
    }
}
