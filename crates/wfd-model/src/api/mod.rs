//! API DTOs (server-api.md): every request and response shape of the HTTP API, owned by T01b (work-breakdown.md §8).
//!
//! | Module | Routes |
//! |---|---|
//! | [`catalog`] | `GET /api/meta`, `/api/catalog`, `/api/weapons/{key}`, `/api/items/{key}`, `/api/enemies/{key}`, `POST /api/candidates` (§5.1-§5.5, §5.7) |
//! | [`schema`] | `GET /api/schema` (§5.6) |
//! | [`calc`] | `POST /api/calc`, `/api/timeline`, `/api/explain` (§6) and the engine's report types |
//! | [`buildcode`] | `POST /api/build/encode`, `/api/build/decode`, `/api/build/export-inspiration` (§7) |
//! | [`opt`] | `POST /api/optimize`, its SSE events, `GET /api/optimize/{job}` (§8) |
//! | [`data`] | `/api/data/*` and the refresh events (§9) |
//! | [`error`] | the body of every non-2xx response (§2) |
//!
//! The documents (`CalcInput` and below, server-api.md §4) are the model types of `crate::scenario` and
//! `crate::build`. Conventions (server-api.md §2, domain-model.md §1): JSON only (no compact form, so optional fields
//! are omitted when absent); requests and responses reject unknown fields; `u64` fields are numbers ≤ 2^53 − 1
//! ([`int53`]); values that may be infinite use `crate::serde_util::ext_f64`. The TypeScript form is generated by
//! `cargo xtask gen-ts` from [`codegen::typescript_files`] (feature `ts`).
//!
//! Where server-api.md differs from the spec or leaves a shape open, the choice is recorded in CONTRACTS.md (T01b).

