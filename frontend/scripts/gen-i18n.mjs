// Merges the per-feature message files `src/i18n/en/<feature>.json` (work-breakdown.md §2.2: one file per feature
// folder, merged at build time) into `src/i18n/en.json` and writes the typed id union `src/i18n/messages.ts`
// (frontend.md §8: an unknown id is a type error). Both outputs are generated, gitignored, and rebuilt by the
// `pre*` npm scripts before dev, build, lint, typecheck and test.
//
// Usage: node scripts/gen-i18n.mjs [--check]
//   --check  exit 1 when the outputs are missing or stale instead of writing them.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src/i18n/en");
const outJson = join(root, "src/i18n/en.json");
const outTs = join(root, "src/i18n/messages.ts");
const check = process.argv.includes("--check");

/** Valid message id: dot-separated segments of letters, digits, `_` and `-` (`toggle.T-13.label`). */
const ID = /^[A-Za-z0-9_-]+(\.[A-Za-z0-9_-]+)*$/;

const merged = {};
const origin = {};
const errors = [];
for (const file of readdirSync(srcDir).filter((f) => f.endsWith(".json")).sort()) {
  let data;
  try {
    data = JSON.parse(readFileSync(join(srcDir, file), "utf8"));
  } catch (e) {
    errors.push(`${file}: ${e.message}`);
    continue;
  }
  if (typeof data !== "object" || data === null || Array.isArray(data)) {
    errors.push(`${file}: the top level must be an object of id → ICU message`);
    continue;
  }
  for (const [id, msg] of Object.entries(data)) {
    if (!ID.test(id)) errors.push(`${file}: invalid message id ${JSON.stringify(id)}`);
    if (typeof msg !== "string") errors.push(`${file}: ${id}: the message must be a string`);
    if (id in merged) errors.push(`${file}: ${id} is already defined in ${origin[id]}`);
    merged[id] = msg;
    origin[id] = file;
  }
}
if (errors.length > 0) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const ids = Object.keys(merged).sort();
const sorted = Object.fromEntries(ids.map((id) => [id, merged[id]]));
const json = JSON.stringify(sorted, null, 2) + "\n";
const ts =
  "// Generated by scripts/gen-i18n.mjs from src/i18n/en/*.json. Do not edit.\n\n" +
  "/** Every UI message id (frontend.md §8). */\n" +
  "export type MessageId =\n" +
  ids.map((id) => `  | ${JSON.stringify(id)}`).join("\n") +
  ";\n\n" +
  `/** Number of message ids. */\nexport const MESSAGE_COUNT = ${ids.length};\n`;

if (check) {
  const stale = [
    [outJson, json],
    [outTs, ts],
  ].filter(([p, text]) => !existsSync(p) || readFileSync(p, "utf8") !== text);
  if (stale.length > 0) {
    console.error(`stale: ${stale.map(([p]) => p).join(", ")} (run npm run gen)`);
    process.exit(1);
  }
} else {
  for (const [p, text] of [
    [outJson, json],
    [outTs, ts],
  ]) {
    if (!existsSync(p) || readFileSync(p, "utf8") !== text) writeFileSync(p, text);
  }
}
