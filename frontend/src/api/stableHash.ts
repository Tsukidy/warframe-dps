// Stable hashing of JSON documents for query keys (frontend.md §5: `useCalcEv` keyed by
// `(data_version, stableHash(doc))`). Object keys are sorted, so two equal documents hash equally whatever the
// insertion order of their fields.

/** Canonical JSON: object keys sorted, `undefined` members dropped (as JSON.stringify does). */
export function stableStringify(value: unknown): string {
  if (value === null || typeof value !== "object") {
    return JSON.stringify(value) ?? "null";
  }
  if (Array.isArray(value)) {
    return `[${value.map((v) => (v === undefined ? "null" : stableStringify(v))).join(",")}]`;
  }
  const obj = value as Record<string, unknown>;
  const keys = Object.keys(obj)
    .filter((k) => obj[k] !== undefined)
    .sort();
  return `{${keys.map((k) => `${JSON.stringify(k)}:${stableStringify(obj[k])}`).join(",")}}`;
}

/** FNV-1a (two 32-bit lanes) of the canonical JSON, as 16 hex digits. */
export function stableHash(value: unknown): string {
  const s = stableStringify(value);
  let h1 = 0x811c9dc5;
  let h2 = 0x01000193 ^ 0x9e3779b9;
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    h1 = Math.imul(h1 ^ c, 16777619);
    h2 = Math.imul(h2 ^ c, 2246822519);
  }
  return (h1 >>> 0).toString(16).padStart(8, "0") + (h2 >>> 0).toString(16).padStart(8, "0");
}
